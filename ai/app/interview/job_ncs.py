_SPACES = re.compile(r"\s+")


def _matches(keyword: str, title: str, compact: str) -> bool:
    # 영문 단어는 다른 영문 단어 안에 포함된 경우(「ai」와 「email」 등)를 제외하고,
    # 한글 단어는 띄어쓰기와 관계없이 비교한다
    if keyword.isascii():
        return re.search(rf"(?<![a-z0-9]){re.escape(keyword)}(?![a-z0-9])", title) is not None
    return keyword in compact


def _groups(job_title: str) -> list[JobGroup]:
    title = job_title.lower()
    compact = _SPACES.sub("", title)
    return [g for g in JOB_GROUPS if any(_matches(k, title, compact) for k in g.keywords)]


def job_subcategories(job_title: str) -> tuple[str, ...]:
    """직무명이 해당하는 모든 직무 묶음의 NCS 세분류를 중복 없이 반환한다.

    해당하는 묶음이 없으면 빈 튜플이다.
    """
    names = (name for group in _groups(job_title) for name in group.subcategories)
    return tuple(dict.fromkeys(names))


def competency_units(subcategories: Sequence[str]) -> tuple[str, ...]:
    """세분류들의 능력단위를 중복 없이 순서대로 반환한다."""
    units = (unit for name in subcategories for unit in COMPETENCY_UNITS.get(name, ()))
    return tuple(dict.fromkeys(units))
